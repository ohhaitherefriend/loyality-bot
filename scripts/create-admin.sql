-- Скрипт для создания администратора
-- 
-- ⚠️ ВАЖНО: Администратор ДОЛЖЕН иметь валидный номер телефона!
-- Новая версия бота требует, чтобы все пользователи (включая админов) 
-- были полностью зарегистрированы перед использованием функций.
--
-- Замените значения на свои и выполните в базе данных

-- ==========================================
-- РЕКОМЕНДУЕМЫЙ СПОСОБ: Через /makeadmin
-- ==========================================
-- 1. Зарегистрируйтесь в боте через /start (введите НАСТОЯЩИЙ номер телефона!)
-- 2. Используйте команду: /makeadmin СЕКРЕТНЫЙ_КОД
-- 3. Секретный код настраивается в переменной окружения: TELEGRAM_BOT_ADMIN_SECRET
--
-- Это самый безопасный способ!

-- ==========================================
-- СПОСОБ 2: Обновить существующего пользователя
-- ==========================================
-- Если пользователь уже зарегистрирован, просто назначьте ему роль ADMIN:

-- Для H2 / PostgreSQL:
UPDATE users 
SET role = 'ADMIN' 
WHERE phone_number = '+79001234567';  -- Замените на свой номер

-- Или по chat_id:
UPDATE users 
SET role = 'ADMIN' 
WHERE chat_id = 123456789;  -- Замените на свой chat_id

-- ==========================================
-- СПОСОБ 3: Создать нового администратора
-- ==========================================
-- ⚠️ ВНИМАНИЕ: Убедитесь, что указываете ВАЛИДНЫЙ номер телефона (10+ цифр)!

-- Для H2:
INSERT INTO users (
    chat_id, 
    phone_number, 
    first_name, 
    last_name, 
    username, 
    monthly_spent,
    role, 
    state, 
    created_at, 
    updated_at,
    last_month_reset
) 
VALUES (
    123456789,              -- YOUR_CHAT_ID (замените на свой!)
    '+79001234567',         -- Ваш НАСТОЯЩИЙ номер телефона (10+ цифр!)
    'Ваше имя',            -- Ваше имя
    'Фамилия',             -- Ваша фамилия (или NULL)
    'username',            -- Ваш username в Telegram (без @)
    0.0,                   -- Начальные траты = 0
    'ADMIN',               -- Роль администратора
    'REGISTERED',          -- Обязательно REGISTERED!
    CURRENT_TIMESTAMP,     -- Дата создания
    CURRENT_TIMESTAMP,     -- Дата обновления
    CURRENT_TIMESTAMP      -- Дата последнего сброса месячных трат
);

-- Для PostgreSQL:
INSERT INTO users (
    chat_id, 
    phone_number, 
    first_name, 
    last_name, 
    username, 
    monthly_spent,
    role, 
    state, 
    created_at, 
    updated_at,
    last_month_reset
) 
VALUES (
    123456789,              -- YOUR_CHAT_ID
    '+79001234567',         -- Ваш НАСТОЯЩИЙ номер телефона
    'Ваше имя', 
    'Фамилия', 
    'username', 
    0.0,
    'ADMIN', 
    'REGISTERED',           -- Обязательно!
    NOW(), 
    NOW(),
    NOW()
)
ON CONFLICT (chat_id) DO UPDATE 
SET role = 'ADMIN', state = 'REGISTERED';

-- ==========================================
-- Как узнать свой CHAT_ID
-- ==========================================
-- 1. Напишите вашему боту /start
-- 2. Посмотрите в логах приложения - там будет ваш chat_id
-- 3. Или используйте бота @userinfobot в Telegram
-- 4. Или посмотрите в базе данных после регистрации

-- ==========================================
-- Проверка после создания
-- ==========================================
-- Проверьте, что администратор создан правильно:
SELECT 
    id,
    chat_id,
    phone_number,
    LENGTH(REGEXP_REPLACE(phone_number, '[^0-9]', '')) as phone_digits,
    first_name,
    role,
    state
FROM users 
WHERE role = 'ADMIN';

-- Убедитесь что:
-- 1. phone_digits >= 10 (минимум 10 цифр в номере)
-- 2. state = 'REGISTERED' (а не 'NEW' или 'AWAITING_PHONE')
-- 3. phone_number не пустой

-- ==========================================
-- ВАЖНО: Что НЕ надо делать
-- ==========================================
-- ❌ НЕ создавайте админа с пустым phone_number
-- ❌ НЕ создавайте админа с state='NEW' или 'AWAITING_PHONE'
-- ❌ НЕ указывайте код покупки (6-8 цифр) вместо телефона
-- ❌ НЕ указывайте chat_id в поле phone_number

-- ==========================================
-- Исправление существующих админов
-- ==========================================
-- Если у вас уже есть админ без номера телефона:

-- 1. Сначала посмотрите проблемных админов:
SELECT * FROM users 
WHERE role = 'ADMIN' 
AND (phone_number IS NULL 
     OR phone_number = '' 
     OR LENGTH(REGEXP_REPLACE(phone_number, '[^0-9]', '')) < 10);

-- 2. Исправьте (замените на настоящий номер):
UPDATE users 
SET 
    phone_number = '+79001234567',  -- Ваш настоящий номер!
    state = 'REGISTERED'
WHERE role = 'ADMIN' 
AND chat_id = 123456789;  -- Ваш chat_id