package com.plstk.loyaltybot.entity.importing;

/**
 * Как трактовать batch относительно предыдущего состояния ассортимента поставщика.
 */
public enum SnapshotMode {
    /** Полный снимок scope: offers, не встреченные в batch, деактивируются после успешного apply. */
    FULL,
    /** Частичное обновление: отсутствие строки ничего не значит, деактивация не выполняется. */
    DELTA
}
